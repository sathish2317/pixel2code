export function safeZipPath(p: string): boolean {
  return (
    p.length > 0 &&
    p.length < 200 &&
    !p.startsWith('/') &&
    !p.includes('..') &&
    !p.includes('\\') &&
    !/^[a-zA-Z]:/.test(p)
  );
}

function readme(p: Project): string {
  const fw: Record<Target, string> = {
    html: 'Plain HTML, CSS and JavaScript.',
    bootstrap: 'Bootstrap 5 (CDN) with custom CSS.',
    tailwind: 'Tailwind CSS (Play CDN) with custom CSS.',
  };
  return `# ${p.name}

Generated by Pixel2Code. Stack: ${fw[p.target]}

## Run it

Option 1: double-click \`index.html\`.

Option 2 (local server, Windows CMD or PowerShell):

\`\`\`
npx serve .
\`\`\`

Then open the address it prints.

## Notes

- Fonts load from Google Fonts, so you need internet for them. Fallback fonts are declared.
- Blocks between \`p2c:head\` / \`p2c:body\` comments are managed by Pixel2Code. Edit freely, but re-applying fonts or animations in the app will rewrite those blocks.
`;
}

export function exportFiles(p: Project): ProjectFile[] {
  const extra: ProjectFile[] = [];
  const has = (n: string) => p.files.some((f) => f.path === n);
  if (!has('README.md')) extra.push({ path: 'README.md', content: readme(p) });
  if (!has('.gitignore')) extra.push({ path: '.gitignore', content: 'node_modules/\n.env\n.DS_Store\n' });
  return [...p.files, ...extra];
}

const rootName = (p: Project) => p.name.replace(/[^\w\- ]+/g, '').trim().replace(/\s+/g, '-') || 'pixel2code-project';

async function zipFiles(root: string, files: ProjectFile[], assets: ProjectAsset[]): Promise<Uint8Array> {
  const zip = new JSZip();
  for (const f of files) {
    if (!safeZipPath(f.path)) throw new Error('Unsafe file path blocked: ' + f.path);
    zip.file(`${root}/${f.path}`, f.content);
  }
  // Images go to the exact paths the code uses (for example images/logo.png), as real binary files.
  for (const a of assets) {
    if (!safeZipPath(a.path)) throw new Error('Unsafe image path blocked: ' + a.path);
    zip.file(`${root}/${a.path}`, a.base64, { base64: true });
  }
  return zip.generateAsync({ type: 'uint8array', compression: 'DEFLATE' });
}

export async function buildZip(p: Project, assets: ProjectAsset[] = []): Promise<Uint8Array> {
  return zipFiles(rootName(p), exportFiles(p), assets);
}

/** Browser download on web, share sheet on phones. */
async function saveBytes(bytes: Uint8Array, filename: string, doneLabel: string): Promise<string> {
  if (Platform.OS === 'web') {
    const blob = new Blob([bytes as BlobPart], { type: 'application/zip' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 5000);
    return `${doneLabel} downloaded: ${filename}`;
  }
  const FS = await import('expo-file-system');
  const Sharing = await import('expo-sharing');
  const file = new FS.File(FS.Paths.cache, filename);
  if (file.exists) file.delete();
  file.create();
  file.write(bytes);
  if (!(await Sharing.isAvailableAsync())) throw new Error('Sharing is not available on this device.');
  await Sharing.shareAsync(file.uri, { mimeType: 'application/zip', dialogTitle: 'Save project ZIP' });
  return `${doneLabel} ready: ${filename}`;
}

/** Saves the HTML/CSS/JS ZIP (the project exactly as it is in the editor). */
export async function exportZip(p: Project, assets: ProjectAsset[] = []): Promise<string> {
  const bytes = await buildZip(p, assets);
  const filename = (p.name.replace(/[^\w\- ]+/g, '').trim().replace(/\s+/g, '-') || 'project') + '.zip';
  return saveBytes(bytes, filename, 'ZIP');
}

export const EXPORT_LABELS: Record<ExportKind, string> = { react: 'React (JavaScript)', 'react-ts': 'React (TypeScript)', assets: 'Images only' };

/** Converts the project to a React/Vite project (JS or TS) or exports only the images, then saves it as a ZIP. */
export async function exportProjectZip(p: Project, assets: ProjectAsset[], kind: ExportKind): Promise<{ message: string; notes: string[] }> {
  const built = buildExport({ name: p.name, target: p.target, files: p.files, assets, kind });
  const bytes = await zipFiles(rootName(p), built.files, built.assets);
  const suffix = kind === 'react' ? '-react' : kind === 'react-ts' ? '-react-ts' : '-images';
  const filename = rootName(p) + suffix + '.zip';
  return { message: await saveBytes(bytes, filename, EXPORT_LABELS[kind]), notes: built.notes };
}

/** Reads a project ZIP (picked file uri) into text files + images. Strips a single top-level folder and blocks bad paths. */
export async function importZipFromUri(uri: string): Promise<{ files: ProjectFile[]; assets: ProjectAsset[] }> {
  const buf = await (await fetch(uri)).arrayBuffer();
  const zip = await readZip(buf);
  const entries = Object.values(zip.files).filter((f) => !f.dir);
  if (entries.length > 600) throw new Error('ZIP has too many files (max 600).');
  const names = entries.map((e) => e.name);
  const top = names[0]?.split('/')[0];
  const strip = top && names.every((n) => n.startsWith(top + '/')) ? top + '/' : '';
  const out: ProjectFile[] = [];
  for (const e of entries) {
    const path = e.name.slice(strip.length);
    if (!safeZipPath(path)) throw new Error('Unsafe path in ZIP: ' + e.name);
    if (/\.(png|jpe?g|webp|gif|ico|svg|avif|bmp|woff2?|ttf|otf|eot|zip)$/i.test(path)) continue; // not text: images are collected below
    if (/(^|\/)(node_modules|__MACOSX)\//.test(path) || /(^|\/)\.DS_Store$/.test(path)) continue;
    out.push({ path, content: await e.async('string') });
  }
  if (!out.length) throw new Error('No text files found in that ZIP.');
  // Images keep their own paths so the imported code still points to them.
  const imgs = await collectAssets(zip, { prefix: '', sanitize: false, maxTotalBytes: ASSET_TOTAL_LIMIT });
  return { files: out, assets: imgs.assets };
}

export async function saveSingleFile(f: ProjectFile): Promise<string> {
  const name = f.path.split('/').pop() || 'file.txt';
  if (Platform.OS === 'web') {
    const url = URL.createObjectURL(new Blob([f.content], { type: 'text/plain' }));
    const a = document.createElement('a');
    a.href = url;
    a.download = name;
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 5000);
    return 'Downloaded ' + name;
  }
  const FS = await import('expo-file-system');
  const Sharing = await import('expo-sharing');
  const file = new FS.File(FS.Paths.cache, name);
  if (file.exists) file.delete();
  file.create();
  file.write(f.content);
  await Sharing.shareAsync(file.uri);
  return 'Shared ' + name;
}

